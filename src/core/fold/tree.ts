/**
 * Tree vocabulary of the functional core — a minimal, read-only view of
 * unist/mdast/hast nodes, so that pure code can traverse and rebuild Markdown
 * trees without depending on any runtime library.
 *
 * The shell (src/adapters/unified/*) hands a tree over at the boundary with a
 * single cast; the core never mutates it: transforms rebuild the spine of the
 * tree (persistent data structure, structural sharing of untouched subtrees)
 * and folds are catamorphisms that only read.
 */
import type { Position } from 'unist';

/** Values allowed in hast `properties` (property-information names: className, ariaLabel, dataKind…). */
export type HastValue = string | number | boolean | null | undefined | readonly (string | number)[];
export type HastProperties = Readonly<Record<string, HastValue>>;

export interface HastText {
  readonly type: 'text';
  readonly value: string;
}
export interface HastElement {
  readonly type: 'element';
  readonly tagName: string;
  readonly properties: HastProperties;
  readonly children: readonly HastChild[];
}
export type HastChild = HastElement | HastText;

/**
 * `node.data` as read by mdast-util-to-hast (hName / hProperties / hChildren)
 * plus the private markers of this project's stages (reading*).
 */
export interface NodeData {
  readonly hName?: string;
  readonly hProperties?: HastProperties;
  readonly hChildren?: readonly HastChild[];
  readonly [key: string]: unknown;
}

/** Any mdast node (or a node of a remark extension: directives, math, custom stage nodes). */
export interface MdNode {
  readonly type: string;
  readonly children?: readonly MdNode[];
  readonly value?: string;
  readonly data?: NodeData;
  readonly position?: Position;
  readonly [key: string]: unknown;
}

/** Node types whose interior a text-oriented stage must never touch (docs/arquitetura.md §4). */
export const OPAQUE_TYPES: ReadonlySet<string> = new Set([
  'code',
  'inlineCode',
  'math',
  'inlineMath',
  'html',
  'yaml',
  'toml',
  'definition',
]);

export const DIRECTIVE_TYPES: ReadonlySet<string> = new Set(['textDirective', 'leafDirective', 'containerDirective']);

export const isDirective = (node: MdNode): boolean => DIRECTIVE_TYPES.has(node.type);

export const directiveName = (node: MdNode): string | undefined => {
  const name = node['name'];
  return isDirective(node) && typeof name === 'string' ? name : undefined;
};

/** Directive attributes (remark-directive maps `#x` to id and `.y` to class). */
export const directiveAttributes = (node: MdNode): Readonly<Record<string, string>> => {
  const raw = node['attributes'];
  if (typeof raw !== 'object' || raw === null) return {};
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(raw as Record<string, unknown>)) {
    if (typeof v === 'string') out[k] = v;
    else if (v === null || v === undefined) out[k] = '';
  }
  return out;
};

export const childrenOf = (node: MdNode): readonly MdNode[] => node.children ?? [];

/** True when an earlier stage already claimed the node (mdast-util-to-hast will render it as hName). */
export const isClaimed = (node: MdNode): boolean => typeof node.data?.hName === 'string';

/** Private marker: the node (and its subtree) was generated by a stage and is not source text. */
export const GENERATED = 'readingGenerated';
export const isGenerated = (node: MdNode): boolean => node.data?.[GENERATED] === true;

/** Source slice of a node, when positions and the source are known. */
export const sourceOf = (node: MdNode, source: string | null): string | null => {
  const start = node.position?.start.offset;
  const end = node.position?.end.offset;
  return source !== null && start !== undefined && end !== undefined ? source.slice(start, end) : null;
};

/**
 * True for an unclaimed text directive that carries neither a label nor
 * attributes — `:30` in "10:30", `:b` in "a:b" — i.e. prose that
 * remark-directive mistook for syntax. The integrity stage restores it verbatim.
 */
export const isProseDirective = (node: MdNode, source: string | null): boolean => {
  if (node.type !== 'textDirective' || isClaimed(node)) return false;
  const raw = sourceOf(node, source);
  return raw !== null && !/[[{]/.test(raw);
};

/**
 * When the visible text is computed.
 *   'pending' — during the reading stage: later stages (concepts, abnt…) will
 *               still claim the text directives that have a label or
 *               attributes, so their label is the best prediction of the text;
 *   'final'   — after every claiming stage (meta): any directive still
 *               unclaimed will be restored verbatim by the integrity stage.
 */
export type TextMode = 'pending' | 'final';

/**
 * Text a reader actually sees for a fragment of the tree, before rehype:
 * like plainText, but unclaimed text directives contribute what the integrity
 * stage will restore (see TextMode). Generated nodes and footnote markers are
 * skipped.
 */
export const visibleText = (node: MdNode, source: string | null, mode: TextMode = 'pending'): string => {
  if (isGenerated(node)) return '';
  if (node.type === 'footnoteReference') return '';
  if (node.type === 'textDirective' && !isClaimed(node)) {
    const raw = sourceOf(node, source);
    if (raw !== null && (mode === 'final' || !/[[{]/.test(raw))) return raw;
  }
  if (typeof node.value === 'string') return node.value;
  const alt = node['alt'];
  if (typeof alt === 'string' && alt.length > 0) return alt;
  return childrenOf(node)
    .map((c) => visibleText(c, source, mode))
    .join('');
};
