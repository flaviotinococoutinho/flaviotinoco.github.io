/**
 * JSON Feed 1.1 (https://www.jsonfeed.org/version/1.1/, read 2026-10-19) — pure builder.
 *
 * One feed per locale, next to the RSS 2.0 feed, with the same items (essays and
 * labs written in that language, newest first). Choices, field by field:
 *   version        "https://jsonfeed.org/version/1.1", first member (the spec asks for it first)
 *   home_page_url  the home page of the locale; feed_url the feed's own URL (both "strongly
 *                  recommended", treated as required for public feeds)
 *   language       BCP 47 tag of the locale (RFC 5646)
 *   authors        the site's author (top level; items inherit it)
 *   items          id = url = the canonical URL (the spec's "ideally the full URL"; it never
 *                  changes because URLs are generated by the bijective route codec);
 *                  summary = the meta description (plain text); content_html = the abstract
 *                  only, as one escaped paragraph — full texts are not duplicated in the feed;
 *                  date_published / date_modified in RFC 3339 (UTC); tags = form and stratum.
 */
import type { Locale } from '../domain/locale.ts';

export const JSON_FEED_VERSION = 'https://jsonfeed.org/version/1.1';
export const JSON_FEED_MEDIA_TYPE = 'application/feed+json';

export type FeedAuthor = { readonly name: string; readonly url: string };

export type FeedItemInput = {
  readonly url: string;
  readonly title: string;
  readonly summary: string;
  /** Plain-text abstract (NBR 6028); the summary stands in when the work has none. */
  readonly abstract?: string;
  readonly published: Date;
  readonly modified: Date;
  readonly tags: readonly string[];
  readonly language: Locale;
};

export type FeedInput = {
  readonly title: string;
  readonly description: string;
  readonly homePageUrl: string;
  readonly feedUrl: string;
  readonly language: Locale;
  readonly authors: readonly FeedAuthor[];
  readonly icon?: string;
  readonly favicon?: string;
  readonly items: readonly FeedItemInput[];
};

export type JsonFeedItem = {
  readonly id: string;
  readonly url: string;
  readonly title: string;
  readonly summary: string;
  readonly content_html: string;
  readonly date_published: string;
  readonly date_modified: string;
  readonly tags: readonly string[];
  readonly language: Locale;
};

export type JsonFeed = {
  readonly version: typeof JSON_FEED_VERSION;
  readonly title: string;
  readonly home_page_url: string;
  readonly feed_url: string;
  readonly description: string;
  readonly icon?: string;
  readonly favicon?: string;
  readonly language: Locale;
  readonly authors: readonly FeedAuthor[];
  readonly items: readonly JsonFeedItem[];
};

const HTML_ESCAPES: Readonly<Record<string, string>> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };

/** Escapes text for HTML content (the abstract is plain text, never markup). */
export const escapeHtml = (s: string): string => s.replace(/[&<>"]/gu, (c) => HTML_ESCAPES[c] ?? c);

/** RFC 3339 timestamp in UTC (Date.prototype.toISOString is an RFC 3339 profile). */
export const rfc3339 = (d: Date): string => d.toISOString();

export const jsonFeedItem = (item: FeedItemInput): JsonFeedItem => ({
  id: item.url,
  url: item.url,
  title: item.title,
  summary: item.summary,
  content_html: `<p>${escapeHtml(item.abstract ?? item.summary)}</p>`,
  date_published: rfc3339(item.published),
  date_modified: rfc3339(item.modified),
  tags: [...item.tags],
  language: item.language,
});

/** The feed, items newest first (ties broken by URL, so the output is a function of the set). */
export const jsonFeed = (input: FeedInput): JsonFeed => ({
  version: JSON_FEED_VERSION,
  title: input.title,
  home_page_url: input.homePageUrl,
  feed_url: input.feedUrl,
  description: input.description,
  ...(input.icon !== undefined ? { icon: input.icon } : {}),
  ...(input.favicon !== undefined ? { favicon: input.favicon } : {}),
  language: input.language,
  authors: [...input.authors],
  items: [...input.items]
    .sort((a, b) => b.published.valueOf() - a.published.valueOf() || (a.url < b.url ? -1 : a.url > b.url ? 1 : 0))
    .map(jsonFeedItem),
});
